import cadquery as cq
outer_width = 80.0
outer_height = 40.0
outer_height = 20.0
wall_thickness = 2.0
rib_width = 6.0
rib_height = 12.0
rib_spacing = 12.0
rib_count = 8
chamfer_size = 0.5
outer = cq.Workplane('XY').rect(outer_width, outer_height).extrude(outer_height)
inner = cq.Workplane('XY').rect(outer_width - 2 * wall_thickness, outer_height - 2 * wall_thickness).extrude(outer_height)
inner = cq.Workplane('XY').rect(outer_width - 2 * wall_thickness, outer_height - 2 * wall_thickness).extrude(outer_height)
inner = inner.cut(inner)
rib = cq.Workplane('XY').rect(outer_width - 2 * wall_thickness, outer_height - 2 * wall_thickness).extrude(outer_height)
rib = rib.translate((0, 0, outer_height - rib_height))
rib = rib.translate((0, 0, outer_height - rib_height))
rib = rib.translate((0, 0, outer_height - rib_height))
combined = outer.union(rib)
combined = combined.edges('|Z').chamfer(chamfer_size)
combined = combined.faces('>Z').workplane().hole(rib_width)
combined = combined.faces('>Z').workplane().center(0, 0).rect(rib_width, rib_height).cutBlind(-rib_width)
result = combined

import cadquery as cq
leaf_length = 80.0
leaf_width = 20.0
leaf_thickness = 5.0
tip_length = leaf_width
tip_width = leaf_width
groove_width = 4.0
groove_depth = 2.0
pin_hole_diameter = 3.0
fillet_radius = 1.0
rib_width = 6.0
rib_height = 2.0
rib_spacing = 12.0
base = cq.Workplane('XY').polyline([(0,0),(leaf_thickness,0),(leaf_thickness,leaf_width),(leaf_thickness,leaf_thickness),(0,leaf_thickness),(0,0)])
leaf = base.faces('>Z').workplane().hole(pin_hole_diameter)
leaf = leaf.edges('|Z').fillet(fillet_radius)
leaf = leaf.edges('>Z').chamfer(fillet_radius)
leaf = leaf.edges('>Z').fillet(fillet_radius)
leaf = leaf.faces('>Z').workplane().center(0,0).rect(groove_width, leaf_width).extrude(groove_depth)
leaf = leaf.faces('>Z').workplane().center(0,leaf_thickness/2).rect(groove_width, leaf_width).extrude(groove_depth)
leaf = leaf.faces('>Z').workplane().center(0,leaf_thickness/2).hole(pin_hole_diameter)
rib = leaf.faces('>Z').workplane().center(0,leaf_thickness/2).rect(rib_width, rib_height).extrude(rib_height)
leaf = leaf.union(rib)
leaf = leaf.faces('>Z').workplane().center(0,leaf_thickness/2).hole(pin_hole_diameter)
leaf = leaf.edges('>Z').fillet(fillet_radius)
leaf = leaf.edges('>Z').chamfer(fillet_radius)
leaf = leaf.edges('>Z').fillet(fillet_radius)
result = leaf

import cadquery as cq
arm_length = 80.0
arm_width = 30.0
arm_thickness = 20.0
shell_thickness = 2.0
rib_width = 20.0
rib_thickness = 3.0
rib_height = arm_thickness + 0.5
fillet_radius = 3.0
slot_width = 5.0
slot_height = 10.0
slot_depth = arm_thickness + 0.5
base = cq.Workplane('XY').box(arm_length, arm_width, arm_thickness)
base = base.edges().fillet(fillet_radius)
base = base.faces('>Z').edges().fillet(fillet_radius)
base = base.faces('>Z').edges().chamfer(0.5)
base = base.faces('>Z').edges().fillet(fillet_radius)
base = base.faces('>Z').edges().fillet(fillet_radius)
base = base.faces('>Z').edges().fillet(fillet_radius)
base = base.faces('>Z').edges().fillet(fillet_radius)
base = base.faces('>Z').edges().fillet(fillet_radius)
base = base.faces('>Z').edges().fillet(fillet_radius)
slot = cq.Workplane('XY').box(slot_width, slot_height, arm_thickness)
slot = slot.rotate((0, 0, 0), (0, 0, 1), 90).translate((0, 0, arm_thickness/2))
base = base.union(slot)
base = base.faces('>Z').edges().fillet(fillet_radius)
base = base.faces('>Z').edges().chamfer(0.5)
base = base.faces('>Z').workplane().center(0, 0).rect(slot_width, slot_height).cutBlind(-slot_depth)
base = base.faces('>Z').workplane().center(0, 0).rect(slot_width, slot_height).extrude(arm_thickness)
base = base.union(base)
base = base.faces('>Z').edges().fillet(fillet_radius)
result = base

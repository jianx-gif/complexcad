import cadquery as cq
outer_radius = 10.0
inner_radius = 12.0
wall_thickness = 2.0
rib_height = 5.0
rib_width = 4.0
rib_thickness = 2.0
rib_spacing = 12.0
chamfer_distance = 0.5
outer_radius = outer_radius - wall_thickness
inner_radius = inner_radius - wall_thickness
rib_count = int(inner_radius + rib_spacing)
base = cq.Workplane('XY').circle(outer_radius).extrude(outer_radius)
inner = cq.Workplane('XY').circle(inner_radius).extrude(inner_radius)
rib = base.cut(inner)
rib = rib.faces('>Z').workplane().hole(inner_radius)
rib = rib.faces('>Z').workplane().hole(inner_radius)
rib = rib.faces('>Z').workplane().hole(rib_thickness)
rib = rib.faces('>Z').workplane().rect(rib_width, rib_thickness).extrude(rib_height)
rib = rib.translate((outer_radius - rib_thickness/2, 0, 0))
rib = rib.translate((outer_radius - rib_thickness/2, 0, 0))
rib = rib.translate((outer_radius - rib_thickness/2, 0, 0))
rib = rib.translate((outer_radius - rib_thickness/2, 0, 0))
rib = rib.translate((outer_radius - rib_thickness/2, 0, 0))
rib = rib.translate((outer_radius - rib_thickness/2, 0, 0))
rib = rib.translate((outer_radius - rib_thickness/2, 0, 0))
rib = rib.translate((outer_radius - rib_thickness/2, 0, 0))
result = rib

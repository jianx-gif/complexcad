import cadquery as cq
outer_radius = 45.0
inner_radius = 20.0
thickness = 10.0
fillet_radius = 5.0
chamfer_distance = 0.5
hole_diameter = 6.0
hole_spacing = 30.0
hole_offset = 15.0
rib_width = 8.0
rib_height = 3.0
rib_thickness = 2.0
rib_spacing = 12.0
rib_count = int((outer_radius - inner_radius) / 2)
base = cq.Workplane('XY').circle(outer_radius).extrude(thickness)
inner_cylinder = cq.Workplane('XY').circle(inner_radius).extrude(thickness)
base = base.cut(inner_cylinder)
hole_positions = [(-hole_spacing/2, 0), (hole_spacing/2, 0)]
base = base.faces('>Z').workplane().pushPoints(hole_positions).hole(hole_diameter)
rib = cq.Workplane('XY').rect(rib_width, rib_height).extrude(rib_thickness)
rib1 = cq.Workplane('XY').rect(rib_width, rib_height).extrude(rib_thickness)
rib2 = rib1.union(rib1).union(rib2)
hole_positions = [(-hole_spacing/2, 0), (hole_spacing/2, 0)]
base = base.union(rib1).union(hole_positions)
base = base.faces('>Z').workplane().pushPoints(hole_positions).hole(hole_diameter)
rib1 = cq.Workplane('XY').rect(rib_width, rib_height).extrude(rib_thickness)
rib2 = rib1.union(rib1).union(rib2)
base = base.union(rib2)
base = base.edges('>Z').chamfer(chamfer_distance)
result = base

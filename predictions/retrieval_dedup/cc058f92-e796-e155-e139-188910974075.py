import cadquery as cq
leg_a = 70
leg_b = 60
thickness = 8
depth = 20
chamfer = 2
counterbore_dia_big = 20
counterbore_depth_big = 4
counterbore_dia = 12
counterbore_depth = 2
blind_hole_dia = 6
blind_hole_depth = 12
rib_width = 4
rib_height = 12
mount_hole_dia = 5
mount_hole_edge = 10
outer_x = leg_a + thickness
outer_y = leg_b + thickness
outer_solid = cq.Workplane('XY').rect(outer_x, outer_y).extrude(depth)
inner_solid = cq.Workplane('XY').rect(leg_a, leg_b).extrude(depth).translate((thickness/2, thickness/2, 0))
base = outer_solid.cut(inner_solid)
base = base.edges("|Z").chamfer(chamfer)
base = base.faces('>Z').workplane().center(thickness/2, thickness/2).cboreHole(counterbore_dia_big, counterbore_depth_big, counterbore_dia, counterbore_depth)
base = base.faces('>Z').workplane().center(leg_a/2, thickness/2).hole(blind_hole_dia, blind_hole_depth)
rib1 = cq.Workplane('XY').rect(rib_width, rib_height).extrude(depth).translate((0, -outer_y/2 + thickness/2, 0))
rib2 = cq.Workplane('XY').rect(rib_width, rib_height).extrude(depth).translate((-outer_x/2 + thickness/2, 0, 0))
base = base.union(rib1).union(rib2)
mount_pts = [(-(outer_x/2) + mount_hole_edge, leg_b/3), (-(outer_x/2) + mount_hole_edge, -leg_b/3)]
base = base.faces('>Z').workplane().pushPoints(mount_pts).hole(mount_hole_dia)
result = base
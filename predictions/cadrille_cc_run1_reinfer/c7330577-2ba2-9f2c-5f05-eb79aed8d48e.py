import cadquery as cq
outer_diameter = 60.0
inner_diameter = 40.0
wall_thickness = 2.0
inner_radius = outer_diameter / 2.0
inner_radius = inner_radius - wall_thickness
rib_width = 6.0
rib_height = 12.0
rib_thickness = 2.0
rib_spacing = 12.0
chamfer_size = 0.5
base = cq.Workplane('XY').circle(outer_diameter / 2.0).extrude(outer_diameter)
inner = cq.Workplane('XY').circle(inner_radius).extrude(outer_diameter)
rib = base.cut(inner)
rib = rib.edges().chamfer(chamfer_size)
rib = rib.edges().chamfer(chamfer_size)
rib = rib.faces('>Z').workplane().hole(inner_radius * 2, inner_radius * 2)
rib = rib.faces('>Z').workplane().rect(rib_width, rib_height).extrude(rib_thickness)
rib = rib.faces('>Z').workplane().rect(rib_width, rib_height).extrude(rib_thickness)
rib = rib.edges('|Z').chamfer(chamfer_size)
result = rib
